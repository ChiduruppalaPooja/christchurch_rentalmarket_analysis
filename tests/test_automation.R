# Offline tests: synthetic inputs only; no downloads or API requests.
source("R/helpers/automation_helpers.R")
automation_test_results <- local({
  results <- list()
  check <- function(value, label) {
    if (!isTRUE(value)) stop("FAIL: ", label)
    results[[length(results) + 1L]] <<- data.frame(check = label, status = "PASS")
  }
  fails <- function(code) inherits(tryCatch({force(code); NULL}, error = identity), "error")
  check(month_date("2026-08") == as.Date("2026-08-01"), "Valid month becomes first-of-month date")
  check(fails(month_date("2026-13")), "Invalid calendar month rejected")
  check(fails(month_date("August")), "Ambiguous month text rejected")
  paths <- monthly_input_paths(month_date("2025-10"), month_date("2026-08"), "data/raw")
  check(length(paths) == 11L, "Extended period has eleven monthly inputs")
  check(tail(paths, 2)[1] == "data/raw/listings_2026_07.csv", "July included")
  check(tail(paths, 1) == "data/raw/listings_2026_08.csv", "August included")
  check(fails(monthly_input_paths(month_date("2026-08"), month_date("2026-07"), ".")), "Reversed dates rejected")
  manifest <- read.csv("config/airbnb_sources.csv", colClasses = "character")
  check(!fails(validate_source_manifest(manifest)), "Official July-August manifest accepted")
  wrong <- manifest; wrong$month[1] <- "2026-08"
  check(fails(validate_source_manifest(wrong)), "Duplicate manifest month rejected")
  wrong <- manifest; wrong$url[1] <- sub("visualisations/listings.csv", "data/listings.csv.gz", wrong$url[1], fixed = TRUE)
  check(fails(validate_source_manifest(wrong)), "Detailed gzip dataset rejected")
  wrong <- manifest; wrong$scrape_date[1] <- "2026-06-12"
  check(fails(validate_source_manifest(wrong)), "Mismatched source date rejected")
  directory <- tempfile("automation-tests-"); dir.create(directory)
  on.exit(unlink(directory, recursive = TRUE), add = TRUE)
  output <- file.path(directory, "result.csv"); writeLines("x\n1", output)
  signature <- list(input = "a", code = "b", config = list(end = "2026-08"))
  state <- list(signature = signature, outputs = file_fingerprints(output))
  check(stage_is_current(state, signature, output), "Unchanged output can be reused")
  altered <- signature; altered$input <- "changed"
  check(!stage_is_current(state, altered, output), "Changed input invalidates cached stage")
  altered <- signature; altered$code <- "changed"
  check(!stage_is_current(state, altered, output), "Changed code invalidates cached stage")
  altered <- signature; altered$config$end <- "2026-09"
  check(!stage_is_current(state, altered, output), "Changed setting invalidates cached stage")
  writeLines("x\n2", output)
  check(!stage_is_current(state, signature, output), "Edited output invalidates cached stage")
  unlink(output)
  check(!stage_is_current(state, signature, output), "Missing output invalidates cached stage")
  html <- file.path(directory, "error.csv"); writeLines("<html>Not a CSV</html>", html)
  check(fails(validate_download(html)), "HTML masquerading as CSV rejected")
  input <- file.path(directory, "input.txt"); writeLines("original", input)
  script <- file.path(directory, "stage.R")
  writeLines("writeLines(readLines(test_input), test_output)", script)
  env <- new.env(parent = globalenv()); env$test_input <- input; env$test_output <- output
  stage_run <- function(name) run_cached_stage(name, input, output, script, list(test = TRUE), directory, env)
  check(stage_run("fixture")$status == "ran", "New stage executes and records its output")
  check(stage_run("fixture")$status == "reused", "Unchanged stage really skips execution")
  writeLines("updated", input)
  check(stage_run("fixture")$status == "ran" && identical(readLines(output), "updated"), "Changed input really regenerates output")
  writeLines("stop('Intentional synthetic stage failure')", script)
  check(fails(stage_run("broken")) && !file.exists(file.path(directory, "broken.rds")), "Failed stage does not record a successful checkpoint")
  writeLines("writeLines(readLines(test_input), test_output)", script)
  check(stage_run("broken")$status == "ran", "Corrected stage can recover after failure")
  do.call(rbind, results)
})
print(automation_test_results)
